// generativeFromConfig resolves a generation model from a config knob holding a
// `provider/model` ref.
func (e *Extension) generativeFromConfig(session, tenant, cfg, capability, locale string) (modelRef string, err error) {
	ref := strings.TrimSpace(e.deps.ResolveConfig(cfg, session, tenant))
	if ref == "" {
		return "", &toolError{msg: tr(locale, "modelNotConfigured", map[string]any{"cfg": cfg, "capability": capability})}
	}
	return ref, nil
}

// storeMedia ingests generated bytes and returns data.files entries.
func (e *Extension) storeMedia(tenant, session, kind string, items []struct {
	Data []byte
	Mime string
}) ([]map[string]any, error) {
	out := make([]map[string]any, 0, len(items))
	for i, it := range items {
		name := fmt.Sprintf("generated-%s-%d-%d", kind, nowMillis(), i)
		code, mime, dispName, err := e.deps.IngestBlob(tenant, session, name, it.Data)
		if err != nil {
			return nil, err
		}
		out = append(out, map[string]any{
			"code": code, "mime": mime, "name": dispName, "bytes": len(it.Data),
		})
	}
	return out, nil
}

func (e *Extension) imageGenerate(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	prompt := strArg(args, "prompt")
	if strings.TrimSpace(prompt) == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "promptRequired", nil)}
	}
	ref, err := e.generativeFromConfig(session, tenant, "model.image", "image", locale)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	client, modelID, err := e.deps.ResolveGenerative("image", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.image", "error": err.Error()})}
	}
	n := 1
	if f, ok := numArg(args, "n"); ok && int(f) > 0 {
		n = int(f)
	}
	files, err := client.GenerateImage(ctx, modelID, prompt, n, strings.TrimSpace(strArg(args, "size")), nil)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	items := make([]struct {
		Data []byte
		Mime string
	}, 0, len(files))
	for _, f := range files {
		items = append(items, struct {
			Data []byte
			Mime string
		}{f.Data, f.MediaType})
	}
	stored, err := e.storeMedia(tenant, session, "image", items)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	lines := []string{tr(locale, "generatedImages", map[string]any{"n": len(stored), "model": modelID})}
	for _, s := range stored {
		lines = append(lines, tr(locale, "fileLine", map[string]any{"code": s["code"], "mime": s["mime"], "bytes": s["bytes"]}))
	}
	return agent.ToolOutcome{Content: strings.Join(lines, "\n"), Metadata: map[string]any{"files": stored, "model": modelID}}, nil
}

func (e *Extension) imageEdit(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	code := strArg(args, "code")
	prompt := strArg(args, "prompt")
	if code == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "codeRequired", nil)}
	}
	if strings.TrimSpace(prompt) == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "promptRequired", nil)}
	}
	ref, err := e.generativeFromConfig(session, tenant, "model.image_edit", "image", locale)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	client, modelID, err := e.deps.ResolveGenerative("image", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.image_edit", "error": err.Error()})}
	}
	_, src, ok := e.deps.BlobGet(tenant, code)
	if !ok {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file not found: file:%s", code)}
	}
	files, err := client.GenerateImage(ctx, modelID, prompt, 1, "", [][]byte{src})
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	items := make([]struct {
		Data []byte
		Mime string
	}, 0, len(files))
	for _, f := range files {
		items = append(items, struct {
			Data []byte
			Mime string
		}{f.Data, f.MediaType})
	}
	stored, err := e.storeMedia(tenant, session, "image", items)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	lines := []string{tr(locale, "editedImages", map[string]any{"n": len(stored), "ref": code, "model": modelID})}
	for _, s := range stored {
		lines = append(lines, tr(locale, "fileLine", map[string]any{"code": s["code"], "mime": s["mime"], "bytes": s["bytes"]}))
	}
	return agent.ToolOutcome{Content: strings.Join(lines, "\n"), Metadata: map[string]any{"files": stored, "model": modelID, "source": code}}, nil
}

func (e *Extension) videoGenerate(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	prompt := strArg(args, "prompt")
	if strings.TrimSpace(prompt) == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "promptRequired", nil)}
	}
	ref, err := e.generativeFromConfig(session, tenant, "model.video", "video", locale)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	client, modelID, err := e.deps.ResolveGenerative("video", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.video", "error": err.Error()})}
	}
	body := map[string]any{"prompt": prompt}
	if v := strings.TrimSpace(strArg(args, "aspect_ratio")); v != "" {
		body["aspectRatio"] = v
	}
	if v := strings.TrimSpace(strArg(args, "resolution")); v != "" {
		body["resolution"] = v
	}
	if code := strings.TrimSpace(strArg(args, "first_frame_code")); code != "" {
		_, data, ok := e.deps.BlobGet(tenant, code)
		if !ok {
			return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("first frame file not found: file:%s", code)}
		}
		body["image"] = base64.StdEncoding.EncodeToString(data)
	}
	if code := strings.TrimSpace(strArg(args, "last_frame_code")); code != "" {
		_, data, ok := e.deps.BlobGet(tenant, code)
		if !ok {
			return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("last frame file not found: file:%s", code)}
		}
		body["lastFrame"] = base64.StdEncoding.EncodeToString(data)
	}
	files, err := client.GenerateVideo(ctx, modelID, body)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	items := make([]struct {
		Data []byte
		Mime string
	}, 0, len(files))
	for _, f := range files {
		items = append(items, struct {
			Data []byte
			Mime string
		}{f.Data, f.MediaType})
	}
	stored, err := e.storeMedia(tenant, session, "video", items)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	lines := []string{tr(locale, "generatedVideos", map[string]any{"n": len(stored), "model": modelID})}
	for _, s := range stored {
		lines = append(lines, tr(locale, "fileLine", map[string]any{"code": s["code"], "mime": s["mime"], "bytes": s["bytes"]}))
	}
	return agent.ToolOutcome{Content: strings.Join(lines, "\n"), Metadata: map[string]any{"files": stored, "model": modelID}}, nil
}

func (e *Extension) ttsGenerate(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	text := strArg(args, "text")
	if strings.TrimSpace(text) == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "textRequired", nil)}
	}
	ref, err := e.generativeFromConfig(session, tenant, "model.speech", "speech", locale)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	client, modelID, err := e.deps.ResolveGenerative("speech", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.speech", "error": err.Error()})}
	}
	audio, err := client.GenerateSpeech(ctx, modelID, text, "", "")
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	stored, err := e.storeMedia(tenant, session, "audio", []struct {
		Data []byte
		Mime string
	}{{audio.Data, audio.MediaType}})
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	code := ""
	if len(stored) > 0 {
		code = fmt.Sprintf("%v", stored[0]["code"])
	}
	return agent.ToolOutcome{
		Content: tr(locale, "synthesized", map[string]any{
			"kib": len(audio.Data) / 1024, "mime": audio.MediaType, "model": modelID, "code": code,
		}),
		Metadata: map[string]any{"files": stored, "model": modelID},
	}, nil
}

func (e *Extension) ttsClone(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	text := strArg(args, "text")
	code := strArg(args, "code")
	if strings.TrimSpace(text) == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "textRequired", nil)}
	}
	if code == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "codeRequired", nil)}
	}
	ref, err := e.generativeFromConfig(session, tenant, "model.speech_clone", "speech", locale)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	client, modelID, err := e.deps.ResolveGenerative("speech", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.speech_clone", "error": err.Error()})}
	}
	meta, data, ok := e.deps.BlobGet(tenant, code)
	if !ok {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file not found: file:%s", code)}
	}
	mime := fmt.Sprintf("%v", meta["mime"])
	if !strings.HasPrefix(mime, "audio/") {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file %s is not audio (mime: %s)", code, mime)}
	}
	voice := fmt.Sprintf("data:%s;base64,%s", mime, base64.StdEncoding.EncodeToString(data))
	audio, err := client.GenerateSpeech(ctx, modelID, text, voice, strings.TrimSpace(strArg(args, "ref_text")))
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	stored, err := e.storeMedia(tenant, session, "audio", []struct {
		Data []byte
		Mime string
	}{{audio.Data, audio.MediaType}})
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	outCode := ""
	if len(stored) > 0 {
		outCode = fmt.Sprintf("%v", stored[0]["code"])
	}
	return agent.ToolOutcome{
		Content: tr(locale, "synthesizedClone", map[string]any{
			"kib": len(audio.Data) / 1024, "mime": audio.MediaType, "model": modelID, "ref": code, "code": outCode,
		}),
		Metadata: map[string]any{"files": stored, "model": modelID, "reference": code},
	}, nil
}

func (e *Extension) audioTranscribe(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	code := strArg(args, "code")
	if code == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "codeRequired", nil)}
	}
	meta, data, ok := e.deps.BlobGet(tenant, code)
	if !ok {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file not found: file:%s", code)}
	}
	mime := fmt.Sprintf("%v", meta["mime"])
	if !strings.HasPrefix(mime, "audio/") {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "notAudio", map[string]any{"code": code, "mime": mime})}
	}
	ref := strings.TrimSpace(e.deps.ResolveConfig("model.transcription", session, tenant))
	if ref == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "transcriptionNotConfigured", nil)}
	}
	client, modelID, err := e.deps.ResolveGenerative("transcription", ref, tenant)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.transcription", "error": err.Error()})}
	}
	text, err := client.Transcribe(ctx, modelID, data, mime)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	if text == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "transcriptionEmpty", nil)}
	}
	return agent.ToolOutcome{
		Content: text,
		Metadata: map[string]any{
			"code": code, "name": meta["name"], "mime": mime, "size": meta["size"], "model": modelID,
		},
	}, nil
}

// imageRead understands a stored image with a vision-capable TEXT model.
func (e *Extension) imageRead(ctx context.Context, tenant, session string, args map[string]any) (agent.ToolOutcome, error) {
	locale := e.localeOf(tenant, session)
	code := strArg(args, "code")
	if code == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "codeRequired", nil)}
	}
	prompt := strArg(args, "prompt")
	if strings.TrimSpace(prompt) == "" {
		prompt = "Describe this image in detail."
	}
	ref := strings.TrimSpace(e.deps.ResolveConfig("model.text", session, tenant))
	if ref == "" {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelNotConfigured", map[string]any{"cfg": "model.text", "capability": "text"})}
	}
	client, modelID, err := e.deps.ResolveTextModel(tenant, ref)
	if err != nil {
		return agent.ToolOutcome{}, &toolError{msg: tr(locale, "modelResolveFailed", map[string]any{"cfg": "model.text", "error": err.Error()})}
	}
	meta, data, ok := e.deps.BlobGet(tenant, code)
	if !ok {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file not found: file:%s", code)}
	}
	mime := fmt.Sprintf("%v", meta["mime"])
	if !strings.HasPrefix(mime, "image/") {
		return agent.ToolOutcome{}, &toolError{msg: fmt.Sprintf("file %s is not an image (mime: %s)", code, mime)}
	}
	text, err := client.Vision(ctx, modelID, prompt, data, mime)
	if err != nil {
		return agent.ToolOutcome{}, err
	}
	return agent.ToolOutcome{Content: text, Metadata: map[string]any{"code": code, "model": modelID}}, nil
}
