// StoreDeps is the host-capability implementation backed by the store + a blob
// reader/writer + the provider registry. It is what agent-go injects into the
// in-process bundled extension (the equivalent of the TS `BundledDeps`).
type StoreDeps struct {
	DB *store.DB
	// BlobGet reads stored file bytes; BlobPut stores generated bytes.
	BlobGetFn func(tenant, code string) (map[string]any, []byte, bool)
	BlobPutFn func(ctx context.Context, tenant, code string, data []byte) error
	// Config resolves a tenant config knob (the agent's `cfg` KV view).
	ConfigFn func(tenant, key string) (string, bool)
	/**
	 * ChannelFn publishes one message onto a channel.
	 *
	 * A FUNCTION RATHER THAN A BUS INTERFACE because that is all the tools need: publish and let the
	 * subscription decide who hears it. Handing them the bus would also hand them the ability to decide
	 * recipients, which is exactly the second routing rule this design removes.
	 */
	ChannelFn func(tenant, channel, topic string, payload any, source string) error
	/**
	 * ExtConfigFn reads an EXTENSION-SCOPED knob.
	 *
	 * IT IS A SEPARATE READER BECAUSE THE TWO ARE STORED IN DIFFERENT KEYSPACES. `SetExtensionConfig`
	 * writes through `config.SetExt`, whose key carries the extension id; `ConfigFn` reads the
	 * tenant-wide keyspace. A bundled tool that only had `ConfigFn` therefore NEVER saw a value the
	 * console had saved for it — the knob displayed as set and the code read "".
	 *
	 * The bundled extension is the only one affected: an out-of-process extension reads its values
	 * through the SDK's `GetConfig`, which already uses the scoped lookup.
	 */
	ExtConfigFn func(tenant, name, session string) (string, bool)
	// SessionVar reads a projected session variable (e.g. locale).
	SessionVarFn func(tenant, session, name string) (string, bool)
	// Mail publishes a mailbox message (bus when wired, else the store queue).
	MailFn func(tenant, session string, typ mailbox.Type, payload any, source string) error
	// OnIngest is called after a generated blob is stored (e.g. media probe).
	OnIngestFn func(ctx context.Context, tenant, code, name, mime string, data []byte)
}

// SessionVariable implements Deps.
func (d *StoreDeps) SessionVariable(tenant, session, name string) (string, bool) {
	if d.SessionVarFn == nil {
		return "", false
	}
	return d.SessionVarFn(tenant, session, name)
}

// ResolveConfig implements Deps (session override → extension-scoped → tenant-wide).
//
// THE EXTENSION-SCOPED LOOKUP COMES FIRST because that is where the console writes. Checking the
// tenant-wide keyspace first would find an unrelated value under the same name and shadow the one the
// user actually set for this extension.
func (d *StoreDeps) ResolveConfig(name, session, tenant string) string {
	if d.ExtConfigFn != nil {
		if v, ok := d.ExtConfigFn(tenant, name, session); ok && v != "" {
			return v
		}
	}
	if d.ConfigFn == nil {
		return ""
	}
	if session != "" {
		if v, ok := d.ConfigFn(tenant, "session."+session+"."+name); ok && v != "" {
			return v
		}
	}
	if v, ok := d.ConfigFn(tenant, name); ok {
		return v
	}
	return ""
}

// ResolveTextModel implements Deps (a `provider/model` ref → v4 client + model).
func (d *StoreDeps) ResolveTextModel(tenant, ref string) (*llm.Client, string, error) {
	prov, model, err := d.providerFor(tenant, ref, "text")
	if err != nil {
		return nil, "", err
	}
	return llm.New(llm.ProviderCredentials{
		ProviderID: prov.ProviderID, BaseURL: prov.BaseURL, APIKey: prov.APIKey,
		Headers: headers(prov.Headers),
	}, nil), model, nil
}

// ResolveGenerative implements Deps (a capability-tagged `provider/model` ref).
func (d *StoreDeps) ResolveGenerative(capability, ref, tenant string) (*llm.Client, string, error) {
	prov, model, err := d.providerFor(tenant, ref, capability)
	if err != nil {
		return nil, "", err
	}
	return llm.New(llm.ProviderCredentials{
		ProviderID: prov.ProviderID, BaseURL: prov.BaseURL, APIKey: prov.APIKey,
		Headers: headers(prov.Headers),
	}, nil), model, nil
}

// providerFor resolves a `provider/model` ref to a provider row + model id,
// validating the provider's capability (semantic grouping).
func (d *StoreDeps) providerFor(tenant, ref, capability string) (store.Provider, string, error) {
	providerID, modelID, ok := splitRef(ref)
	if !ok {
		return store.Provider{}, "", fmt.Errorf("no model selected — set a %s model as \"provider_id/model_id\" (got %q)", capability, ref)
	}
	rows, err := d.DB.ListProviders(tenant)
	if err != nil {
		return store.Provider{}, "", err
	}
	for _, p := range rows {
		if p.ProviderID != providerID {
			continue
		}
		if c := p.Capability; c != "" && c != capability {
			return store.Provider{}, "", fmt.Errorf("provider %q serves %q, not %q", providerID, c, capability)
		}
		return p, modelID, nil
	}
	return store.Provider{}, "", fmt.Errorf("provider not found: %s", providerID)
}

// BlobGet implements Deps.
func (d *StoreDeps) BlobGet(tenant, code string) (map[string]any, []byte, bool) {
	if d.BlobGetFn == nil {
		return nil, nil, false
	}
	return d.BlobGetFn(tenant, code)
}

// IngestBlob implements Deps.
func (d *StoreDeps) IngestBlob(tenant, session, name string, data []byte) (string, string, string, error) {
	code := newCode()
	mime := sniffMime(data)
	if d.BlobPutFn != nil {
		if err := d.BlobPutFn(context.Background(), tenant, code, data); err != nil {
			return "", "", "", err
		}
	}
	_, _ = d.DB.UpsertFile(store.AgentFile{
		Code: code, Tenant: tenant, SHA256: sha256Hex(data), Name: name,
		Mime: mime, Size: int64(len(data)), UploaderSession: session,
	})
	if d.OnIngestFn != nil {
		d.OnIngestFn(context.Background(), tenant, code, name, mime, data)
	}
	return code, mime, name, nil
}

