func toStoreTodos(rows []TodoRow) []struct {
	Content  string
	Status   string
	Priority string
} {
	out := make([]struct {
		Content  string
		Status   string
		Priority string
	}, 0, len(rows))
	for _, r := range rows {
		out = append(out, struct {
			Content  string
			Status   string
			Priority string
		}{r.Content, r.Status, r.Priority})
	}
	return out
}

var _ agent.ToolRegistry = (*Extension)(nil)

func splitRef(ref string) (string, string, bool) {
	i := strings.IndexByte(ref, '/')
	if i <= 0 || i == len(ref)-1 {
		return "", "", false
	}
	return ref[:i], ref[i+1:], true
}

func headers(raw string) map[string]string {
	if raw == "" || raw == "null" {
		return nil
	}
	m := map[string]string{}
	if err := json.Unmarshal([]byte(raw), &m); err != nil {
		return nil
	}
	return m
}

func sha256Hex(data []byte) string {
	h := sha256.Sum256(data)
	return hex.EncodeToString(h[:])
}

// newCode mints a 16-char content code (the `file:<code>` segment).
func newCode() string {
	var b [8]byte
	_, _ = rand.Read(b[:])
	return hex.EncodeToString(b[:])
}

// sniffMime derives a content type from the leading bytes.
func sniffMime(b []byte) string {
	switch {
	case len(b) >= 8 && string(b[:8]) == "\x89PNG\r\n\x1a\n":
		return "image/png"
	case len(b) >= 3 && b[0] == 0xFF && b[1] == 0xD8 && b[2] == 0xFF:
		return "image/jpeg"
	case len(b) >= 6 && (string(b[:6]) == "GIF87a" || string(b[:6]) == "GIF89a"):
		return "image/gif"
	case len(b) >= 12 && string(b[4:8]) == "ftyp":
		return "video/mp4"
	case len(b) >= 4 && string(b[:4]) == "RIFF":
		return "audio/wav"
	case len(b) >= 4 && string(b[:4]) == "OggS":
		return "audio/ogg"
	case len(b) >= 3 && string(b[:3]) == "ID3":
		return "audio/mpeg"
	case len(b) >= 2 && b[0] == 0xFF && (b[1]&0xE0) == 0xE0:
		return "audio/mpeg"
	default:
		return "application/octet-stream"
	}
}

/**
 * The group channel's wire shape, duplicated from agentbus because bundled is imported BY agentbus.
 *
 * THEY ARE PINNED BY A TEST in agentbus that fails if either side renames: a silent divergence here
 * would publish to a subject nobody subscribes to, and the symptom — a message that is sent and never
 * arrives — is the exact failure this whole design exists to make impossible.
 */
const groupChannel = "group"

// newGroupMessageID is a fresh id for one transcript row.
func newGroupMessageID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return fmt.Sprintf("gm-%d", time.Now().UnixNano())
	}
	return hex.EncodeToString(b[:])
}

func groupTopicTo(group, session string) string {
	return group + ".to." + session
}
