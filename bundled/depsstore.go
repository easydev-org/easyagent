/**
 * CreateGroupForSession implements Deps: a group with exactly two people in it.
 *
 * IT CANNOT CREATE ANY OTHER SHAPE. The signature takes one coordinator and derives the group from
 * one worker, so an extension cannot build a group with three members or invite a session it did not
 * fork — the narrow shape IS the restriction. `group.create` gates the call before it gets here.
 */
func (d *StoreDeps) CreateGroupForSession(tenant, group, coordinator string) error {
	now := time.Now().UTC().Format(time.RFC3339)
	return d.DB.CreateGroup(tenant, store.Group{
		Name: group, CreatedBy: "session:" + coordinator, CreatedAt: now, UpdatedAt: now,
	}, coordinator, nil, now)
}

/**
 * PostGroupMessage implements Deps: store the message, then deliver it.
 *
 * THE ORDER IS THE CONTRACT. A message exists in the transcript before any member hears it, so a recipient
 * can always find what it received and a reader who joins later can see it. Delivering first would allow a
 * message to be heard and never recorded — the one failure that cannot be repaired, because there is
 * nothing to point at.
 *
 * A DELIVERY FAILURE IS RETURNED, because at this layer the caller is a tool whose whole job that message
 * was. The message is already stored either way; the error says the recipients were not reached.
 */
func (d *StoreDeps) PostGroupMessage(tenant, group, from string, to []string, text string, attachments []string) error {
	/**
	 * THE ATTACHMENT REFERENCES ARE RESOLVED AGAINST THE BLOB STORE, not taken on trust.
	 *
	 * The tool hands over bare codes; the blob record is what says a code exists, what it is and how big. Storing
	 * a code nobody ingested would put a tile in the transcript that every member sees and nothing can load.
	 */
	attachmentsJSON := d.encodeAttachments(tenant, attachments)
	msg, err := d.DB.AppendGroupMessage(store.GroupMessage{
		ID: newGroupMessageID(), Tenant: tenant, Group: group,
		Sender: from, SenderName: d.sessionName(tenant, from), Body: text,
		Attachments: attachmentsJSON,
	}, time.Now().UTC().Format(time.RFC3339Nano))
	if err != nil {
		return err
	}
	if d.ChannelFn == nil {
		return fmt.Errorf("deliver group message: channels are not configured")
	}
	// THE SUBJECT IS BUILT HERE FROM LITERALS, not from agentbus constants: bundled is imported BY
	// agentbus, so naming them would be an import cycle. The two strings are pinned by a test in
	// agentbus that asserts its own constants match, so a rename on one side cannot drift silently.
	var firstErr error
	for _, rcpt := range to {
		payload := map[string]any{
			"group": group, "from": from, "from_name": msg.SenderName, "text": text,
			"message_id": msg.ID, "seq": msg.Seq,
		}
		// THE FILES RIDE WITH THE DELIVERY: a woken member reads the prompt built from this payload, so a
		// picture that only reached the transcript would be one nobody was told about.
		if files := d.attachmentPayload(tenant, attachments); len(files) > 0 {
			payload["attachments"] = files
		}
		if err := d.ChannelFn(tenant, groupChannel, groupTopicTo(group, rcpt), payload, "session:"+from); err != nil && firstErr == nil {
			firstErr = err
		}
	}
	return firstErr
}

/**
 * encodeAttachments turns bare codes into the stored JSON form, filling type and size from the blob record.
 *
 * A CODE NOBODY INGESTED IS DROPPED, for the same reason the group RPC drops an empty one: a reference that
 * names no blob would render as a tile that never loads, with nothing to tell the reader whether the sender or
 * the reader is at fault.
 */
func (d *StoreDeps) encodeAttachments(tenant string, codes []string) string {
	if len(codes) == 0 {
		return ""
	}
	type stored struct {
		Code string `json:"code"`
		Name string `json:"name"`
		Size int32  `json:"size"`
		Mime string `json:"mime"`
	}
	out := make([]stored, 0, len(codes))
	seen := make(map[string]bool, len(codes))
	for _, code := range codes {
		code = strings.TrimSpace(code)
		if code == "" || seen[code] {
			continue
		}
		seen[code] = true
		a := stored{Code: code}
		if rec, ok, err := d.DB.FileByCode(tenant, code); err == nil && ok {
			a.Name, a.Mime, a.Size = rec.Name, rec.Mime, int32(rec.Size)
		} else {
			// AN UNRESOLVABLE CODE IS NOT STORED AT ALL — it names nothing.
			continue
		}
		out = append(out, a)
	}
	if len(out) == 0 {
		return ""
	}
	b, err := json.Marshal(out)
	if err != nil {
		return ""
	}
	return string(b)
}

/**
 * attachmentPayload is the delivery form of the same references: the shape the distributor turns into prompt
 * text and the console turns into attachments.
 */
func (d *StoreDeps) attachmentPayload(tenant string, codes []string) []map[string]any {
	out := make([]map[string]any, 0, len(codes))
	seen := make(map[string]bool, len(codes))
	for _, code := range codes {
		code = strings.TrimSpace(code)
		if code == "" || seen[code] {
			continue
		}
		rec, ok, err := d.DB.FileByCode(tenant, code)
		if err != nil || !ok {
			continue
		}
		seen[code] = true
		out = append(out, map[string]any{
			"code": rec.Code, "name": rec.Name, "size": int32(rec.Size), "mime": rec.Mime,
		})
	}
	return out
}

// sessionName returns a session's display label, or "" when it cannot be read. The label is cosmetic in a
// transcript, so a read failure must not fail the post.
func (d *StoreDeps) sessionName(tenant, sid string) string {
	if sid == "" {
		return ""
	}
	if row, ok, _ := d.DB.GetSession(tenant, sid); ok {
		return row.Name
	}
	return ""
}

// PublishMailbox implements Deps.
func (d *StoreDeps) PublishMailbox(tenant, session string, typ mailbox.Type, payload any, source string) error {
	if d.MailFn == nil {
		// REFUSING IS DELIBERATE. The fallback used to be a direct write to the store's queue, which
		// only worked while the queue lived in the relational database. It does not any more, so a
		// deployment that forgot to wire this would silently deliver nothing — and a tool that says it
		// sent something it did not is worse than one that says it cannot.
		return fmt.Errorf("publish mailbox: no queue configured")
	}
	return d.MailFn(tenant, session, typ, payload, source)
}

// MessageChain implements Deps (oldest-first; limit <= 0 = no cap).
func (d *StoreDeps) MessageChain(tenant, tip string, limit int) []ChainEntry {
	if limit <= 0 {
		limit = 1_000_000 // effectively uncapped
	}
	msgs, err := d.DB.Chain(tenant, tip, limit, "")
	if err != nil {
		return nil
	}
	out := make([]ChainEntry, 0, len(msgs))
	// Chain already returns oldest-first, which is the order callers expect; the position comes from
	// the row, not from the walk.
	for _, m := range msgs {
		out = append(out, ChainEntry{
			ID: m.ID, Role: m.Role, CreatedAt: m.CreatedAt,
			Seq: m.Seq, Source: m.Source,
		})
	}
	return out
}

